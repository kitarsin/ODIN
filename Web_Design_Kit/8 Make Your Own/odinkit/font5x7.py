def _build():
    glyphs = {}
    for ch, rows in _RAW.items():
        rows = list(rows) + ["....."] * (GLYPH_H - len(rows))
        assert len(rows) == GLYPH_H, ch
        for r in rows:
            assert len(r) == GLYPH_W, (ch, r)
        glyphs[ch] = [[c == "#" for c in r] for r in rows]
    return glyphs


GLYPHS = _build()
